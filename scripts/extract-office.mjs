// Turns an AgentWorld scene bundle (office/*.json) into static files the app can serve:
// the background and every character frame go to public/, the layout goes to lib/office-scene.ts.
// Usage: npm run office:extract [-- office/office_1.json] [--background=/file.png]
// --background uses an image already in public/ instead of the bundle's background; it must be the same size.
import { access, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const args = process.argv.slice(2);
const backgroundArg = args.find((arg) => arg.startsWith("--background="))?.slice("--background=".length);
const source = path.resolve(root, args.find((arg) => !arg.startsWith("--")) ?? "office/office_1.json");
const bundle = JSON.parse(await readFile(source, "utf8"));

if (bundle.type !== "agentworld-scene-bundle") throw new Error(`${source} isn't an AgentWorld scene bundle.`);

function decode(dataUrl) {
  const match = /^data:image\/(png|webp|jpeg);base64,(.+)$/s.exec(dataUrl ?? "");
  if (!match) throw new Error("Expected a base64 PNG, WebP or JPEG data URL.");
  return { ext: match[1] === "jpeg" ? "jpg" : match[1], bytes: Buffer.from(match[2], "base64") };
}

const slug = (value) => String(value).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const { office } = bundle;
let backgroundPath;
if (backgroundArg) {
  backgroundPath = `/${backgroundArg.replace(/^\/+/, "")}`;
  await access(path.join(root, "public", backgroundPath));
} else {
  const background = decode(office.background);
  backgroundPath = `/office-space.${background.ext}`;
  await writeFile(path.join(root, "public", backgroundPath), background.bytes);
}

const outDir = path.join(root, "public", "office");
await rm(outDir, { recursive: true, force: true });

const seats = [];
for (const seat of bundle.seats) {
  const { character } = seat;
  const dir = path.join(outDir, slug(character.id));
  await mkdir(dir, { recursive: true });

  const frames = [];
  const typing = character.animations?.typing?.length ? character.animations.typing : [character.sprite];
  for (const [index, frame] of typing.entries()) {
    const image = decode(frame);
    const file = `typing-${index}.${image.ext}`;
    await writeFile(path.join(dir, file), image.bytes);
    frames.push(`/office/${slug(character.id)}/${file}`);
  }

  seats.push({
    id: seat.id,
    label: seat.label,
    x: seat.x,
    y: seat.y,
    width: seat.width,
    zIndex: seat.zIndex,
    character: { id: character.id, width: character.width, height: character.height, frames },
  });
}

const scene = { name: office.name, width: office.width, height: office.height, background: backgroundPath, seats };
await writeFile(
  path.join(root, "lib", "office-scene.ts"),
  `// Generated by scripts/extract-office.mjs from ${path.relative(root, source)}. Don't edit by hand.
import type { OfficeScene } from "@/lib/office";

export const OFFICE_SCENE: OfficeScene = ${JSON.stringify(scene, null, 2)};
`,
);

console.log(`Extracted ${seats.length} seats and ${seats.reduce((n, s) => n + s.character.frames.length, 0)} frames from ${office.name}.`);
